using System;
using System.Collections.Generic;
using System.IO;
using Hung.Base.Editor;
using NUnit.Framework;

namespace Hung.Base.Editor.Tests
{
    public sealed class StableIdCodeGeneratorTests
    {
        private static KeyValuePair<string, string> Row(string code, string value) => new(code, value);

        [Test]
        public void GenerateContent_SortsByValueAndSkipsReservedPrefix()
        {
            string content = StableIdCodeGenerator.GenerateContent(
                "AudioId",
                "Hung.Base",
                "GameAudioIds",
                new[] { Row("Hit", "bumphero.sfx.hit"), Row("Click", "base.ui.click"), Row("Home", "bumphero.bgm.home") },
                "base.");

            const string expected =
                "// <auto-generated />\n" +
                "using Hung.Base;\n" +
                "\n" +
                "public static class GameAudioIds\n" +
                "{\n" +
                "    public static readonly AudioId Home = new(\"bumphero.bgm.home\");\n" +
                "    public static readonly AudioId Hit = new(\"bumphero.sfx.hit\");\n" +
                "}\n";

            Assert.AreEqual(expected, content);
        }

        [TestCase("1Hit")]
        [TestCase("Hit Sound")]
        [TestCase("Hit-Sound")]
        public void GenerateContent_InvalidCodeName_Throws(string code)
        {
            var ex = Assert.Throws<InvalidOperationException>(() =>
                StableIdCodeGenerator.GenerateContent(
                    "AudioId",
                    "Hung.Base",
                    "GameAudioIds",
                    new[] { Row(code, "bumphero.sfx.hit") },
                    "base."));

            StringAssert.Contains(code, ex.Message);
        }

        [Test]
        public void GenerateContent_DuplicateCodeName_Throws()
        {
            var ex = Assert.Throws<InvalidOperationException>(() =>
                StableIdCodeGenerator.GenerateContent(
                    "AudioId",
                    "Hung.Base",
                    "GameAudioIds",
                    new[] { Row("Hit", "bumphero.sfx.hit"), Row("Hit", "bumphero.sfx.hit_2") },
                    "base."));

            StringAssert.Contains("Hit", ex.Message);
        }

        [Test]
        public void GenerateContent_EscapedAndUnescapedSameName_Throws()
        {
            Assert.Throws<InvalidOperationException>(() => StableIdCodeGenerator.GenerateContent(
                "AudioId", "Hung.Base", "GameAudioIds",
                new[] { Row("Hit", "game.hit"), Row("@Hit", "game.other") }, "base."));
        }

        [TestCase("class", false)]
        [TestCase("event", false)]
        [TestCase("@class", true)]
        [TestCase("@event", true)]
        [TestCase("Hit", true)]
        [TestCase("@Hit", true)]
        [TestCase("record", true)]
        public void IsValidCodeName_RespectsReservedKeywords(string name, bool expected)
        {
            Assert.That(StableIdCodeGenerator.IsValidCodeName(name), Is.EqualTo(expected));
        }

        [TestCase("class")]
        [TestCase("event")]
        public void GenerateContent_UnescapedKeyword_Throws(string name)
        {
            Assert.Throws<InvalidOperationException>(() => StableIdCodeGenerator.GenerateContent(
                "AudioId", "Hung.Base", "GameAudioIds", new[] { Row(name, "game.hit") }, "base."));
        }

        [Test]
        public void WriteIfChanged_SameContent_IsNoOp()
        {
            string path = Path.Combine(Path.GetTempPath(), "GameAudioIds.g.cs");
            string content = StableIdCodeGenerator.GenerateContent(
                "AudioId",
                "Hung.Base",
                "GameAudioIds",
                new[] { Row("Hit", "bumphero.sfx.hit") },
                "base.");

            File.WriteAllText(path, content);
            DateTime timestamp = File.GetLastWriteTimeUtc(path);

            Assert.IsFalse(StableIdCodeGenerator.WriteIfChanged(path, content));
            Assert.AreEqual(timestamp, File.GetLastWriteTimeUtc(path));

            File.Delete(path);
        }
    }
}
