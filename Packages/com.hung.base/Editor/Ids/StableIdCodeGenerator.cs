using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Text;
using System.Text.RegularExpressions;
using UnityEditor;

namespace Hung.Base.Editor
{
    /// <summary>Shared code generator emitting C# static classes with strongly-typed identifier constants.</summary>
    public static class StableIdCodeGenerator
    {
        private static readonly Regex CodeNameRegex = new(
            "^@?[A-Za-z_][A-Za-z0-9_]*$",
            RegexOptions.CultureInvariant | RegexOptions.Compiled);

        private static readonly HashSet<string> ReservedKeywords = new(StringComparer.Ordinal)
        {
            "abstract", "as", "base", "bool", "break", "byte", "case", "catch", "char",
            "checked", "class", "const", "continue", "decimal", "default", "delegate", "do",
            "double", "else", "enum", "event", "explicit", "extern", "false", "finally",
            "fixed", "float", "for", "foreach", "goto", "if", "implicit", "in", "int",
            "interface", "internal", "is", "lock", "long", "namespace", "new", "null",
            "object", "operator", "out", "override", "params", "private", "protected",
            "public", "readonly", "ref", "return", "sbyte", "sealed", "short", "sizeof",
            "stackalloc", "static", "string", "struct", "switch", "this", "throw", "true",
            "try", "typeof", "uint", "ulong", "unchecked", "unsafe", "ushort", "using",
            "virtual", "void", "volatile", "while"
        };

        /// <summary>Validates that a string is a valid C# identifier suitable for a generated constant name.</summary>
        /// <param name="codeName">The code name to validate.</param>
        /// <returns><c>true</c> if valid; otherwise, <c>false</c>.</returns>
        public static bool IsValidCodeName(string codeName)
        {
            return !string.IsNullOrEmpty(codeName) && CodeNameRegex.IsMatch(codeName) &&
                   (codeName[0] == '@' || !ReservedKeywords.Contains(codeName));
        }

        /// <summary>Generates source file content containing a static class with typed identifier constants.</summary>
        /// <param name="idTypeName">The simple name of the identifier struct type (e.g., "ItemId" or "AudioId").</param>
        /// <param name="idNamespace">The namespace containing the identifier type.</param>
        /// <param name="className">The name of the static class to generate.</param>
        /// <param name="codeNameToValue">Mapping of constant member names to raw identifier values.</param>
        /// <param name="reservedPrefix">Prefix string to skip (e.g., "base."), or null/empty to skip nothing.</param>
        /// <returns>Generated C# file content with LF line endings.</returns>
        /// <exception cref="InvalidOperationException">Thrown when a code name is invalid or duplicated.</exception>
        public static string GenerateContent(
            string idTypeName,
            string idNamespace,
            string className,
            IEnumerable<KeyValuePair<string, string>> codeNameToValue,
            string reservedPrefix)
        {
            List<KeyValuePair<string, string>> rows = (codeNameToValue ?? Array.Empty<KeyValuePair<string, string>>()).ToList();

            if (!string.IsNullOrEmpty(reservedPrefix))
            {
                rows = rows.Where(kvp => kvp.Value == null || !kvp.Value.StartsWith(reservedPrefix, StringComparison.Ordinal)).ToList();
            }

            var seenNames = new HashSet<string>(StringComparer.Ordinal);
            foreach (KeyValuePair<string, string> kvp in rows)
            {
                if (!IsValidCodeName(kvp.Key))
                    throw new InvalidOperationException($"Code name '{kvp.Key}' is invalid.");

                string identifier = kvp.Key[0] == '@' ? kvp.Key.Substring(1) : kvp.Key;
                if (!seenNames.Add(identifier))
                    throw new InvalidOperationException($"Code name '{kvp.Key}' is duplicated.");
            }

            rows = rows.OrderBy(kvp => kvp.Value, StringComparer.Ordinal).ToList();

            var builder = new StringBuilder();
            builder.AppendLine("// <auto-generated />");
            builder.AppendLine($"using {idNamespace};");
            builder.AppendLine();
            builder.AppendLine($"public static class {className}");
            builder.AppendLine("{");

            foreach (KeyValuePair<string, string> kvp in rows)
            {
                builder.AppendLine($"    public static readonly {idTypeName} {kvp.Key} = new(\"{kvp.Value}\");");
            }

            builder.AppendLine("}");
            return builder.ToString().Replace("\r\n", "\n");
        }

        /// <summary>Writes content to disk only if changed, creating parent directories and importing into AssetDatabase.</summary>
        /// <param name="path">Absolute file path.</param>
        /// <param name="content">File content to write.</param>
        /// <returns><c>true</c> if the file was written; <c>false</c> if unchanged.</returns>
        public static bool WriteIfChanged(string path, string content)
        {
            content = content.Replace("\r\n", "\n");
            if (File.Exists(path) && File.ReadAllText(path).Replace("\r\n", "\n") == content)
                return false;

            Directory.CreateDirectory(Path.GetDirectoryName(path));
            File.WriteAllText(path, content);
            AssetDatabase.ImportAsset(ToAssetPath(path));
            return true;
        }

        private static string ToAssetPath(string path)
        {
            string normalized = path.Replace("\\", "/");
            string project = Directory.GetCurrentDirectory().Replace("\\", "/") + "/";
            return normalized.StartsWith(project, StringComparison.Ordinal)
                ? normalized.Substring(project.Length)
                : normalized;
        }
    }
}
